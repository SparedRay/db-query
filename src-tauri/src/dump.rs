//! Assembling a script that recreates a schema.
//!
//! **Pure.** Nothing here talks to a server: it takes definitions somebody
//! else fetched and decides what the file says and in what order. That is
//! deliberate — the ordering rules are where this feature is subtle, and a
//! rule that can only be checked by dumping a database is a rule that gets
//! checked once.
//!
//! The one claim everything serves: **the script re-runs against an empty
//! server, top to bottom, in one go.** See `docs/stage-22-schema-export.md` §4.

use std::collections::{BTreeMap, BTreeSet};

use crate::schema::{EventRef, TriggerRef};

/// How much of a schema to write.
#[derive(Debug, Clone, Copy, PartialEq, Eq, serde::Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum Contents {
    SchemaOnly,
    SchemaAndData,
    DataOnly,
}

impl Contents {
    pub fn wants_schema(self) -> bool {
        !matches!(self, Self::DataOnly)
    }
    pub fn wants_data(self) -> bool {
        !matches!(self, Self::SchemaOnly)
    }
}

#[derive(Debug, Clone, serde::Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct DumpOptions {
    pub contents: Contents,
    /// `DROP … IF EXISTS` before each object, so the script can be run twice.
    pub drop_existing: bool,
    /// `CREATE DATABASE IF NOT EXISTS` and `USE` per database.
    pub create_database: bool,
    /// Strip `DEFINER=…` from views, routines, triggers and events.
    pub omit_definer: bool,
    /// Rows per `INSERT`. Defaulted from Settings; see §9.5.
    pub batch_rows: usize,
    /// And a ceiling in bytes, because the row count alone says nothing about
    /// a table of `TEXT` columns. Whichever comes first.
    pub batch_bytes: usize,
}

/// `mysqldump`'s own `--net-buffer-length` default, and for the same reason:
/// `max_allowed_packet` belongs to the server the script is *loaded* into,
/// which the server it was dumped from cannot see. 1 MB is accepted
/// everywhere.
pub const DEFAULT_BATCH_BYTES: usize = 1_046_528;

impl Default for DumpOptions {
    fn default() -> Self {
        Self {
            contents: Contents::SchemaAndData,
            drop_existing: true,
            create_database: true,
            omit_definer: true,
            batch_rows: 1_000,
            batch_bytes: DEFAULT_BATCH_BYTES,
        }
    }
}

// ----------------------------------------------------------------- header

/// What the script sets before it does anything, and why each line is there.
///
/// Every one of these is restored by [`footer`]. A script that leaves a
/// session with foreign-key checks off is a trap for whatever runs in it next.
pub fn header(note: &str) -> String {
    format!(
        "-- {note}\n\
         --\n\
         -- Generated by db-query. Re-runnable top to bottom against an empty server.\n\
         \n\
         SET @OLD_FOREIGN_KEY_CHECKS = @@FOREIGN_KEY_CHECKS;\n\
         -- Off so tables can be written in any order. With them on, a correct\n\
         -- script would need the whole schema topologically sorted, and MySQL\n\
         -- permits foreign-key cycles, which would make that impossible.\n\
         SET FOREIGN_KEY_CHECKS = 0;\n\
         SET @OLD_SQL_MODE = @@SQL_MODE;\n\
         -- Without NO_AUTO_VALUE_ON_ZERO a literal 0 in an AUTO_INCREMENT\n\
         -- column is replaced by the next sequence value on load: the row\n\
         -- silently changes its primary key, and every foreign key pointing\n\
         -- at it becomes wrong.\n\
         SET SQL_MODE = 'NO_AUTO_VALUE_ON_ZERO';\n\
         SET @OLD_TIME_ZONE = @@TIME_ZONE;\n\
         SET TIME_ZONE = '+00:00';\n\
         SET NAMES utf8mb4;\n\n"
    )
}

pub fn footer() -> String {
    "\n-- Everything the header changed, put back.\n\
     SET FOREIGN_KEY_CHECKS = @OLD_FOREIGN_KEY_CHECKS;\n\
     SET SQL_MODE = @OLD_SQL_MODE;\n\
     SET TIME_ZONE = @OLD_TIME_ZONE;\n"
        .to_string()
}

// ------------------------------------------------------------- the DEFINER

/// Remove a `DEFINER=\`user\`@\`host\`` clause.
///
/// A dump carrying a definer that does not exist on the target server fails
/// to load, and the common reason to export a schema is to put it somewhere
/// else. Off keeps the dump faithful; on makes it portable.
///
/// Deliberately narrow: it matches the exact shape MySQL emits — the keyword,
/// `=`, a quoted user, `@`, a quoted host — and leaves anything else alone.
/// A looser rule would eventually eat the word out of a view's own text.
pub fn strip_definer(sql: &str) -> String {
    let Some(at) = sql.find("DEFINER=") else {
        return sql.to_string();
    };
    let rest = &sql[at + "DEFINER=".len()..];
    let Some(user_end) = quoted_end(rest) else {
        return sql.to_string();
    };
    let after_user = &rest[user_end..];
    if !after_user.starts_with('@') {
        return sql.to_string();
    }
    let Some(host_end) = quoted_end(&after_user[1..]) else {
        return sql.to_string();
    };
    let end = at + "DEFINER=".len() + user_end + 1 + host_end;
    // Take the space that separated it from the next word too, so stripping
    // does not leave a double space in the middle of a statement.
    let tail = sql[end..].strip_prefix(' ').unwrap_or(&sql[end..]);
    format!("{}{}", &sql[..at], tail)
}

/// The byte just past a backtick- or single-quoted run starting at 0.
fn quoted_end(s: &str) -> Option<usize> {
    let bytes = s.as_bytes();
    let quote = *bytes.first()?;
    if quote != b'`' && quote != b'\'' {
        return None;
    }
    let mut i = 1;
    while i < bytes.len() {
        if bytes[i] == quote {
            // A doubled quote is an escaped one and does not end the run.
            if bytes.get(i + 1) == Some(&quote) {
                i += 2;
                continue;
            }
            return Some(i + 1);
        }
        i += 1;
    }
    None
}

// --------------------------------------------------------------- ordering

/// Views, ordered so each is created after everything it reads.
///
/// `edges` is `(viewer, viewed)` among views only — a view's dependency on a
/// base table decides nothing, because every table is written before any view.
///
/// Returns `Err` with the names involved if the graph does not resolve. MySQL
/// will not let you build a cycle of views, so that is a "cannot happen" —
/// which is exactly why it returns a value rather than looping or panicking.
pub fn order_views(
    views: &[String],
    edges: &[(String, String)],
) -> Result<Vec<String>, Vec<String>> {
    let present: BTreeSet<&str> = views.iter().map(|v| v.as_str()).collect();
    // Deterministic: a dump that reorders itself between runs is a dump nobody
    // can diff. BTree everywhere, and ties broken by name.
    let mut needs: BTreeMap<&str, BTreeSet<&str>> = views
        .iter()
        .map(|v| (v.as_str(), BTreeSet::new()))
        .collect();
    for (viewer, viewed) in edges {
        // An edge to something not being exported is not a constraint on the
        // order of what is.
        if present.contains(viewer.as_str()) && present.contains(viewed.as_str()) {
            needs.entry(viewer.as_str()).or_default().insert(viewed);
        }
    }

    let mut out: Vec<String> = Vec::with_capacity(views.len());
    let mut done: BTreeSet<&str> = BTreeSet::new();
    while out.len() < views.len() {
        let ready: Vec<&str> = needs
            .iter()
            .filter(|(name, deps)| !done.contains(*name) && deps.iter().all(|d| done.contains(d)))
            .map(|(name, _)| *name)
            .collect();
        if ready.is_empty() {
            let stuck: Vec<String> = needs
                .keys()
                .filter(|n| !done.contains(*n))
                .map(|n| n.to_string())
                .collect();
            return Err(stuck);
        }
        for name in ready {
            done.insert(name);
            out.push(name.to_string());
        }
    }
    Ok(out)
}

/// Triggers, in the order they must be created.
///
/// **The order is the whole point.** `SHOW CREATE TRIGGER` emits no `FOLLOWS`
/// or `PRECEDES`, so two triggers sharing a table, timing and event run in the
/// order they were created — and `ACTION_ORDER` is the only record of it.
/// Created in the wrong order they load without complaint and compute
/// different values.
pub fn order_triggers(triggers: &[TriggerRef]) -> Vec<TriggerRef> {
    let mut out = triggers.to_vec();
    out.sort_by(|a, b| {
        a.table
            .cmp(&b.table)
            .then(a.timing.cmp(&b.timing))
            .then(a.event.cmp(&b.event))
            .then(a.action_order.cmp(&b.action_order))
            // Names only to break a tie that cannot happen, so the output is
            // deterministic whatever the server returns.
            .then(a.name.cmp(&b.name))
    });
    out
}

/// Events, by name. They have no order between them: nothing an event does
/// depends on another event existing.
pub fn order_events(events: &[EventRef]) -> Vec<EventRef> {
    let mut out = events.to_vec();
    out.sort_by(|a, b| a.name.cmp(&b.name));
    out
}

// ------------------------------------------------------------ the sections

/// `USE` and, optionally, the `CREATE DATABASE` before it.
pub fn database_section(db: &str, create: bool) -> Result<String, String> {
    let quoted = crate::sqlgen::quote_ident(db)?;
    let mut out = format!("\n--\n-- Database: {db}\n--\n");
    if create {
        out.push_str(&format!("CREATE DATABASE IF NOT EXISTS {quoted};\n"));
    }
    // Always, whether or not the database is created here. A trigger body
    // names its tables unqualified, so the script has to be *in* the database
    // before one is created — measured, §9.2.
    out.push_str(&format!("USE {quoted};\n"));
    Ok(out)
}

/// One object, wrapped in whatever it needs to mean the same thing.
///
/// `sql_mode` is set and restored around triggers and events because the mode
/// they were written under changes what they compute. `time_zone` likewise
/// for events, whose `STARTS` is an absolute timestamp read in one.
pub fn object_section(
    heading: &str,
    drop_statement: Option<&str>,
    body: &str,
    sql_mode: Option<&str>,
    time_zone: Option<&str>,
) -> String {
    let mut out = format!("\n-- {heading}\n");
    if let Some(drop) = drop_statement {
        out.push_str(drop);
        if !drop.ends_with('\n') {
            out.push('\n');
        }
    }
    let wrapped = sql_mode.is_some() || time_zone.is_some();
    if wrapped {
        out.push_str("SET @SAVE_SQL_MODE = @@SQL_MODE, @SAVE_TIME_ZONE = @@TIME_ZONE;\n");
        if let Some(mode) = sql_mode {
            out.push_str(&format!(
                "SET SQL_MODE = {};\n",
                crate::sqlgen::quote_string(mode)
            ));
        }
        if let Some(tz) = time_zone {
            out.push_str(&format!(
                "SET TIME_ZONE = {};\n",
                crate::sqlgen::quote_string(tz)
            ));
        }
    }
    out.push_str(body.trim_end());
    if !body.trim_end().ends_with(';') {
        out.push(';');
    }
    out.push('\n');
    if wrapped {
        out.push_str("SET SQL_MODE = @SAVE_SQL_MODE, TIME_ZONE = @SAVE_TIME_ZONE;\n");
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn view(names: &[&str]) -> Vec<String> {
        names.iter().map(|n| n.to_string()).collect()
    }
    fn edge(a: &str, b: &str) -> (String, String) {
        (a.to_string(), b.to_string())
    }
    fn trig(name: &str, table: &str, timing: &str, event: &str, order: u32) -> TriggerRef {
        TriggerRef {
            name: name.into(),
            table: table.into(),
            timing: timing.into(),
            event: event.into(),
            action_order: order,
        }
    }

    // ------------------------------------------------------------- views

    /// The probe fixture's chain: `v3 → v2 → v1 → t`. Created in the order
    /// the server lists them, `v2` fails because `v1` does not exist yet.
    #[test]
    fn a_view_is_created_after_the_views_it_reads() {
        let out = order_views(
            &view(&["v3", "v2", "v1"]),
            &[edge("v2", "v1"), edge("v3", "v2")],
        )
        .unwrap();
        assert_eq!(out, view(&["v1", "v2", "v3"]));
    }

    /// Edges to base tables never reach this function, and an edge to a view
    /// somebody did not select is not a constraint on the ones they did.
    #[test]
    fn a_dependency_outside_the_selection_is_not_a_constraint() {
        let out = order_views(&view(&["v2"]), &[edge("v2", "v1")]).unwrap();
        assert_eq!(out, view(&["v2"]));
    }

    /// Two runs of the same export have to produce the same bytes, or nobody
    /// can diff two dumps.
    #[test]
    fn independent_views_come_out_in_a_stable_order() {
        let names = view(&["zebra", "apple", "mango"]);
        let first = order_views(&names, &[]).unwrap();
        assert_eq!(first, view(&["apple", "mango", "zebra"]));
        assert_eq!(order_views(&names, &[]).unwrap(), first);
    }

    /// MySQL will not build one, which is exactly why this returns a value
    /// rather than spinning.
    #[test]
    fn a_cycle_is_reported_rather_than_looped_over() {
        let err = order_views(&view(&["a", "b"]), &[edge("a", "b"), edge("b", "a")]).unwrap_err();
        assert_eq!(err, view(&["a", "b"]));
    }

    // ---------------------------------------------------------- triggers

    /// **The finding from §9.2.** Two `BEFORE INSERT` triggers on one table
    /// have an order recorded only in `ACTION_ORDER`, and the server can
    /// return them in any order at all.
    #[test]
    fn triggers_sharing_a_timing_keep_the_order_only_action_order_records() {
        let out = order_triggers(&[
            trig("second", "t", "BEFORE", "INSERT", 2),
            trig("first", "t", "BEFORE", "INSERT", 1),
        ]);
        assert_eq!(
            out.iter().map(|t| t.name.as_str()).collect::<Vec<_>>(),
            ["first", "second"],
            "alphabetical order would have passed this test backwards"
        );
    }

    /// And the name is not what decides it, which the test above cannot show
    /// on its own.
    #[test]
    fn action_order_beats_the_name() {
        let out = order_triggers(&[
            trig("aaa", "t", "BEFORE", "INSERT", 2),
            trig("zzz", "t", "BEFORE", "INSERT", 1),
        ]);
        assert_eq!(
            out.iter().map(|t| t.name.as_str()).collect::<Vec<_>>(),
            ["zzz", "aaa"]
        );
    }

    #[test]
    fn triggers_are_grouped_by_table_then_timing_then_event() {
        let out = order_triggers(&[
            trig("b_del", "b", "AFTER", "DELETE", 1),
            trig("a_ins", "a", "BEFORE", "INSERT", 1),
            trig("a_upd", "a", "BEFORE", "UPDATE", 1),
            trig("a_after", "a", "AFTER", "INSERT", 1),
        ]);
        assert_eq!(
            out.iter().map(|t| t.name.as_str()).collect::<Vec<_>>(),
            ["a_after", "a_ins", "a_upd", "b_del"]
        );
    }

    // ----------------------------------------------------------- DEFINER

    #[test]
    fn a_definer_is_removed_from_the_shape_mysql_emits() {
        assert_eq!(
            strip_definer("CREATE DEFINER=`root`@`localhost` TRIGGER `t` AFTER INSERT ON `x`"),
            "CREATE TRIGGER `t` AFTER INSERT ON `x`"
        );
        assert_eq!(
            strip_definer(
                "CREATE ALGORITHM=UNDEFINED DEFINER=`root`@`%` SQL SECURITY DEFINER VIEW `v` AS select 1"
            ),
            "CREATE ALGORITHM=UNDEFINED SQL SECURITY DEFINER VIEW `v` AS select 1",
            "only the DEFINER= clause goes; SQL SECURITY DEFINER is a different thing"
        );
    }

    /// Single quotes are as valid as backticks here, and a host can hold a
    /// character that needs them.
    #[test]
    fn a_quoted_user_or_host_is_handled_either_way() {
        assert_eq!(
            strip_definer("CREATE DEFINER='some user'@'10.0.0.%' EVENT `e` ON SCHEDULE"),
            "CREATE EVENT `e` ON SCHEDULE"
        );
    }

    /// Nothing to remove, nothing removed — including from a view whose own
    /// text contains the word.
    #[test]
    fn text_that_only_mentions_the_word_is_left_alone() {
        for sql in [
            "CREATE VIEW `v` AS select 1",
            "CREATE VIEW `v` AS select 'DEFINER=' as x",
        ] {
            assert_eq!(strip_definer(sql), sql);
        }
    }

    // ----------------------------------------------------------- sections

    /// `USE` is emitted whether or not the database is created, because a
    /// trigger body names its tables unqualified — §9.2.
    #[test]
    fn the_database_section_always_switches_into_it() {
        let with = database_section("poc", true).unwrap();
        assert!(with.contains("CREATE DATABASE IF NOT EXISTS `poc`;"));
        assert!(with.contains("USE `poc`;"));

        let without = database_section("poc", false).unwrap();
        assert!(!without.contains("CREATE DATABASE"));
        assert!(without.contains("USE `poc`;"), "{without}");
    }

    /// The name goes into the statement as an identifier, so it is quoted by
    /// `quote_ident` rather than interpolated — a backtick is doubled, and the
    /// one byte that has no escape is refused outright rather than stripped,
    /// because a stripped NUL produces a *different* identifier that might
    /// name a real database.
    #[test]
    fn a_database_name_reaches_the_script_as_a_quoted_identifier() {
        let out = database_section("has`backtick", true).unwrap();
        assert!(out.contains("USE `has``backtick`;"), "{out}");
        assert!(database_section("has\0nul", true).is_err());
    }

    /// A trigger is wrapped in the `sql_mode` it was written under, and the
    /// wrapping is put back afterwards.
    #[test]
    fn an_object_is_wrapped_in_the_session_settings_it_needs() {
        let out = object_section(
            "Trigger t_after_ins",
            Some("DROP TRIGGER IF EXISTS `t_after_ins`;"),
            "CREATE TRIGGER `t_after_ins` AFTER INSERT ON `t` FOR EACH ROW SET @x = 1",
            Some("STRICT_TRANS_TABLES"),
            None,
        );
        assert!(out.contains("DROP TRIGGER IF EXISTS"));
        assert!(out.contains("SET @SAVE_SQL_MODE = @@SQL_MODE"));
        assert!(out.contains("SET SQL_MODE = 'STRICT_TRANS_TABLES';"));
        assert!(out.contains("SET SQL_MODE = @SAVE_SQL_MODE"));
        // And the statement itself is terminated, which the server's text is
        // not.
        assert!(out.contains("SET @x = 1;\n"), "{out}");
    }

    /// An object that needs no session settings gets none, rather than a pair
    /// of no-op lines around every table in the file.
    #[test]
    fn an_object_with_nothing_to_restore_is_not_wrapped() {
        let out = object_section("Table t", None, "CREATE TABLE `t` (`id` int);", None, None);
        assert!(!out.contains("@SAVE_SQL_MODE"), "{out}");
        assert!(out.contains("CREATE TABLE `t` (`id` int);"));
    }

    /// Doubling a terminator produces an empty statement, which some clients
    /// reject.
    #[test]
    fn a_body_that_already_ends_in_a_semicolon_does_not_get_a_second() {
        let out = object_section(
            "Table t",
            None,
            "CREATE TABLE `t` (`id` int);\n",
            None,
            None,
        );
        assert!(!out.contains(";;"), "{out}");
    }

    // ------------------------------------------------------ header/footer

    /// Everything the header changes, the footer puts back. Asserted as a set
    /// rather than by eye, so a line added to one and not the other fails.
    #[test]
    fn the_footer_restores_everything_the_header_saved() {
        let h = header("poc");
        let f = footer();
        for var in ["@OLD_FOREIGN_KEY_CHECKS", "@OLD_SQL_MODE", "@OLD_TIME_ZONE"] {
            assert!(
                h.contains(&format!("SET {var} =")),
                "header never saved {var}"
            );
            assert!(
                f.contains(&format!("= {var};")),
                "footer never restored {var}"
            );
        }
    }

    /// The two lines that are correctness rather than tidiness.
    #[test]
    fn the_header_turns_off_the_two_things_that_corrupt_a_load() {
        let h = header("poc");
        assert!(h.contains("SET FOREIGN_KEY_CHECKS = 0;"));
        assert!(h.contains("NO_AUTO_VALUE_ON_ZERO"));
    }
}
